(* Portable build-time configuration for ocaml-hexaly.
 *
 * Runs at build time (driven by dune). Emits four files into ../ :
 *   c_flags.sexp           -I flag for headers (real) or empty (mock)
 *   cxx_flags.sexp         -I flag for headers (real) or empty (mock)
 *   c_library_flags.sexp   -L + -l<libname> + rpath + C++ runtime (real)
 *                          or just C++ runtime (mock)
 *   hexaly_shim.cpp        One-line #include of the active backend
 *
 * Backend selection (highest priority first):
 *   1. HEXALY_BACKEND={real,mock} env var
 *   2. HEXALY_HOME set and points at a valid install -> real
 *   3. Auto-detect Hexaly under common install paths -> real
 *   4. Fall back to -> mock
 *
 * Cross-platform: uses dune-configurator's portable abstractions for
 * platform detection and avoids POSIX-only commands. *)

module C = Configurator.V1

let getenv k = try Some (Sys.getenv k) with Not_found -> None

let dir_exists p = try Sys.is_directory p with _ -> false

let write_file file contents =
  let oc = open_out file in
  output_string oc contents;
  close_out oc

(* "/opt", "/Library", "$HOME", "C:/" are searched for "hexaly_*" subdirs. *)
let candidate_search_roots () =
  let home = match getenv "HOME" with Some h -> [h] | None -> [] in
  let win  = match getenv "ProgramFiles" with Some p -> [p] | None -> [] in
  [ "/opt"; "/Library"; "/usr/local" ] @ home @ win @ [ "C:/" ]

let starts_with ~prefix s =
  let lp = String.length prefix in
  String.length s >= lp && String.sub s 0 lp = prefix

let ends_with ~suffix s =
  let ls = String.length s and lp = String.length suffix in
  ls >= lp && String.sub s (ls - lp) lp = suffix

let scan_dir d =
  if dir_exists d then try Array.to_list (Sys.readdir d) with _ -> []
  else []

let auto_detect_home () =
  candidate_search_roots ()
  |> List.concat_map (fun base ->
       scan_dir base
       |> List.filter (starts_with ~prefix:"hexaly_")
       |> List.map (Filename.concat base))
  |> List.find_opt (fun d ->
       dir_exists (Filename.concat d "include")
       && dir_exists (Filename.concat d "bin"))

let find_home () =
  match getenv "HEXALY_HOME" with
  | Some h when dir_exists (Filename.concat h "include") -> Some h
  | _ -> auto_detect_home ()

(* Find libhexaly<version>.{dylib,so,dll} and extract the -l name. *)
let find_lib_name lib_dir =
  let entries = scan_dir lib_dir in
  let strip_lib s = if starts_with ~prefix:"lib" s then String.sub s 3 (String.length s - 3) else s in
  let strip_ext s =
    [".dylib"; ".so"; ".dll"]
    |> List.find_map (fun ext ->
         if ends_with ~suffix:ext s then Some (String.sub s 0 (String.length s - String.length ext))
         else None)
    |> Option.value ~default:s
  in
  let names =
    entries
    |> List.filter_map (fun n ->
         let base = strip_ext (strip_lib n) in
         if starts_with ~prefix:"hexaly" base then Some base else None)
    |> List.sort_uniq compare
  in
  (* Prefer the highest-versioned suffix if multiple exist. *)
  match List.rev names with
  | n :: _ -> Some n
  | []     -> None

(* Pick the C++ standard library link flag for the host. *)
let cxx_runtime_flag c =
  match C.ocaml_config_var c "system" with
  | Some "macosx" -> ["-lc++"]
  | Some "linux"
  | Some "linux_eabi"
  | Some "linux_eabihf" -> ["-lstdc++"]
  | Some "mingw64"
  | Some "mingw"
  | Some "win32"
  | Some "win64"        -> [] (* MSVC links its own; mingw links libstdc++ automatically *)
  | _ -> []

let rpath_flag c lib_dir =
  match C.ocaml_config_var c "system" with
  | Some "macosx" -> ["-Wl,-rpath," ^ lib_dir]
  | Some s when starts_with ~prefix:"linux" s -> ["-Wl,-rpath=" ^ lib_dir]
  | _ -> []

let sexp_list items =
  let escape s =
    (* Sexp atoms generally don't need escaping unless they have whitespace
       or special chars; our flags have neither. *)
    s
  in
  "(" ^ String.concat " " (List.map escape items) ^ ")\n"

let pick_backend () =
  match getenv "HEXALY_BACKEND" with
  | Some "real" -> `Real
  | Some "mock" -> `Mock
  | Some other  ->
    prerr_endline ("ERROR: HEXALY_BACKEND must be 'real' or 'mock', got '" ^ other ^ "'");
    exit 1
  | None ->
    (match find_home () with Some _ -> `Real | None -> `Mock)

let shim_include backend =
  let backend_str = match backend with `Real -> "real" | `Mock -> "mock" in
  Printf.sprintf
    "/* Auto-generated by config/discover.ml — do not edit. */\n#include \"hexaly_shim_%s.cpp\"\n"
    backend_str

let emit_real c =
  let home = match find_home () with
    | Some h -> h
    | None ->
      prerr_endline "ERROR: HEXALY_BACKEND=real but no Hexaly install found.";
      prerr_endline "Set HEXALY_HOME or install Hexaly from https://www.hexaly.com/download.";
      exit 1
  in
  let inc = Filename.concat home "include" in
  let lib = Filename.concat home "bin" in
  let lib_name = match find_lib_name lib with
    | Some n -> n
    | None ->
      prerr_endline ("ERROR: no libhexaly* shared library found in " ^ lib);
      exit 1
  in
  let inc_flags = sexp_list ["-I" ^ inc] in
  let lib_flags =
    sexp_list (
      ("-L" ^ lib)
      :: ("-l" ^ lib_name)
      :: (rpath_flag c lib)
      @ cxx_runtime_flag c)
  in
  write_file "c_flags.sexp"         inc_flags;
  write_file "cxx_flags.sexp"       inc_flags;
  write_file "c_library_flags.sexp" lib_flags;
  write_file "hexaly_shim.cpp"      (shim_include `Real);
  prerr_endline ("configure: backend=real, HEXALY_HOME=" ^ home ^ ", lib=-l" ^ lib_name)

let emit_mock c =
  let cxxrt = cxx_runtime_flag c in
  write_file "c_flags.sexp"         "()\n";
  write_file "cxx_flags.sexp"       "()\n";
  write_file "c_library_flags.sexp" (sexp_list cxxrt);
  write_file "hexaly_shim.cpp"      (shim_include `Mock);
  prerr_endline "configure: backend=mock (Hexaly not installed)"

let () =
  C.main ~name:"hexaly-discover" (fun c ->
    match pick_backend () with
    | `Real -> emit_real c
    | `Mock -> emit_mock c)
